-- =============================================================================
-- PROYECTO: DATA MART DE VENTAS Y RENTABILIDAD · TECNONOVA RETAIL
-- CASO: Caso 2 - Retail TecnoNova (U2)
-- MOTOR OBJETIVO: PostgreSQL 14+ / ANSI SQL
-- Implementación Física DDL del Esquema Dimensional
-- =============================================================================
--
-- MEMORIA DE ARQUITECTURA Y DELIMITACIÓN DE ALCANCE:
--
-- 1. DELIMITACIÓN ESTRICTA DEL ALCANCE (OLAP vs. OLTP):
--    Este script implementa EXCLUSIVAMENTE la capa dimensional (tablas DIM_ y FACT_).
--    Las entidades 'PAGO_VENTA' y 'METODO_PAGO' pertenecen funcionalmente al modelo
--    relacional operacional/transaccional en 3NF (Entregable 2), donde resuelven la 
--    Primera Forma Normal (1NF) para apartados y anticipos (Regla #3).
--    En este Data Mart se omiten deliberadamente para prevenir la trampa de abanico 
--    (Fan Trap) en el grano de línea de producto; el seguimiento de saldos y abonos 
--    se delega a un Data Mart satélite de Tesorería.
--
-- 2. POLÍTICA DE INTEGRIDAD Y CERO NULOS (Zero-NULL Foreign Key Policy):
--    En apego a la metodología de Ralph Kimball, se prohíbe el uso de NULL en llaves 
--    foráneas dentro de las tablas de hechos. Cada una de las 7 dimensiones conformadas 
--    incluye un registro centinela con clave sustituta SK = -1 ('No aplica / Desconocido').
--    Esto previene la exclusión silenciosa de métricas al ejecutar INNER JOINs en 
--    herramientas de Business Intelligence (Power BI, Tableau) y resuelve escenarios 
--    como ventas de autoservicio digital (sin asesor) o ventas de servicios puros (sin hardware).
--
-- 3. RESOLUCIÓN DE REGLAS DE NEGOCIO EN CAPA ETL:
--    - Regla #5 (Precios según método de pago y promociones): Las variaciones monetarias 
--      por instrumento de cobro (descuentos en efectivo o recargos por tarjeta) se 
--      absorben y liquidan durante el pipeline de extracción/transformación (ETL) a nivel 
--      atómico dentro de 'precio_unitario' y 'monto_descuento'.
--    - Hito contable de apartados: La tabla FACT_VENTAS únicamente captura ventas 
--      liquidadas y formalmente entregadas. Los productos en proceso de abono se auditan 
--      en la métrica 'cantidad_apartada' de FACT_STOCK.
--
-- 4. PREPARACIÓN ARQUITECTÓNICA DE INVENTARIO:
--    La tabla FACT_STOCK se incluye formalmente bajo el patrón 'Periodic Snapshot' 
--    para viabilizar el cálculo de rotación financiera requerido por la dirección, 
--    documentando que recibirá cargas cuando se integre el sistema de almacenes (WMS).
-- =============================================================================

