-- -----------------------------------------------------------------------------
-- 2.1 FACT_VENTAS
-- Grano: Un renglón o ítem individual facturado dentro de una transacción liquidada.
-- Llaves de Grano: venta_sk (PK técnica) y la pareja (num_ticket, num_linea) UNIQUE.
-- Hito de Realización: Se carga únicamente cuando la venta ha sido liquidada y entregada.
-- -----------------------------------------------------------------------------
CREATE TABLE FACT_VENTAS (
    -- Surrogate key física del hecho (optimización de direccionamiento e indexación en PG)
    venta_sk                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- Llaves foráneas a dimensiones conformadas (Garantía de Cero Nulos)
    tiempo_sk                   INTEGER NOT NULL REFERENCES DIM_TIEMPO(tiempo_sk),
    producto_sk                 INTEGER NOT NULL REFERENCES DIM_PRODUCTO(producto_sk),
    servicio_sk                 INTEGER NOT NULL REFERENCES DIM_SERVICIO(servicio_sk),
    cliente_sk                  INTEGER NOT NULL REFERENCES DIM_CLIENTE(cliente_sk),
    sucursal_sk                 INTEGER NOT NULL REFERENCES DIM_SUCURSAL(sucursal_sk),
    canal_sk                    INTEGER NOT NULL REFERENCES DIM_CANAL(canal_sk),
    asesor_sk                   INTEGER NOT NULL REFERENCES DIM_ASESOR(asesor_sk),

    -- Dimensiones degeneradas (Atributos de auditoría sin tabla satélite)
    num_ticket                  VARCHAR(30)  NOT NULL,
    num_linea                   SMALLINT     NOT NULL,
    numero_serie                VARCHAR(50), -- Capturado si DIM_PRODUCTO.requiere_serie = TRUE
    lote_compra                 VARCHAR(30), -- Regla #7: Trazabilidad de costos por lote de compra
    tiene_garantia_extendida    BOOLEAN      NOT NULL DEFAULT FALSE, -- Flag para cálculo instantáneo de Attach Rate

    -- Métricas cuantitativas almacenadas
    cantidad                    SMALLINT      NOT NULL CHECK (cantidad > 0),
    precio_unitario             NUMERIC(12,2) NOT NULL CHECK (precio_unitario >= 0),   -- No aditiva
    costo_unitario_real         NUMERIC(12,2) NOT NULL CHECK (costo_unitario_real >= 0), -- No aditiva (Costo real de lote)
    monto_bruto                 NUMERIC(14,2) NOT NULL,   -- Aditiva: cantidad * precio_unitario
    monto_descuento             NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (monto_descuento >= 0), -- Aditiva
    monto_neto_venta            NUMERIC(14,2) NOT NULL,   -- Aditiva: monto_bruto - monto_descuento
    costo_total_real            NUMERIC(14,2) NOT NULL,   -- Aditiva: cantidad * costo_unitario_real
    margen_bruto                NUMERIC(14,2) NOT NULL,   -- Aditiva: monto_neto_venta - costo_total_real
    monto_comision_marketplace  NUMERIC(14,2) NOT NULL DEFAULT 0, -- Aditiva: Deducción contractual de intermediario
    margen_neto_real            NUMERIC(14,2) NOT NULL,   -- Aditiva: margen_bruto - monto_comision_marketplace

    -- Restricciones de integridad relacional y consistencia matemática
    CONSTRAINT uq_fact_ventas_ticket_linea UNIQUE (num_ticket, num_linea),
    CONSTRAINT chk_monto_bruto  CHECK (monto_bruto = cantidad * precio_unitario),
    CONSTRAINT chk_monto_neto   CHECK (monto_neto_venta = monto_bruto - monto_descuento),
    CONSTRAINT chk_costo_total  CHECK (costo_total_real = cantidad * costo_unitario_real),
    CONSTRAINT chk_margen_bruto CHECK (margen_bruto = monto_neto_venta - costo_total_real),
    CONSTRAINT chk_margen_neto  CHECK (margen_neto_real = margen_bruto - monto_comision_marketplace)
);

COMMENT ON TABLE FACT_VENTAS IS 
    'Hecho transaccional principal. Grano atómico a nivel de renglón facturado de venta liquidada y entregada.';
COMMENT ON COLUMN FACT_VENTAS.tiene_garantia_extendida IS 
    'Bandera analítica desnormalizada. Evita auto-joins reflexivos para computar el Attach Rate.';
COMMENT ON COLUMN FACT_VENTAS.costo_unitario_real IS 
    'Costo real de adquisición del lote vendido (Regla #7), superando costos estándar teóricos.';
COMMENT ON COLUMN FACT_VENTAS.monto_comision_marketplace IS 
    'Monto monetario de comisión retenido por plataformas digitales de intermediación (Amazon, ML).';

-- Índices B-Tree dedicados sobre llaves foráneas para evitar escaneos secuenciales (Full Table Scans)
CREATE INDEX ix_fact_ventas_tiempo   ON FACT_VENTAS USING BTREE (tiempo_sk);
CREATE INDEX ix_fact_ventas_producto ON FACT_VENTAS USING BTREE (producto_sk);
CREATE INDEX ix_fact_ventas_servicio ON FACT_VENTAS USING BTREE (servicio_sk);
CREATE INDEX ix_fact_ventas_cliente  ON FACT_VENTAS USING BTREE (cliente_sk);
CREATE INDEX ix_fact_ventas_sucursal ON FACT_VENTAS USING BTREE (sucursal_sk);
CREATE INDEX ix_fact_ventas_canal    ON FACT_VENTAS USING BTREE (canal_sk);
CREATE INDEX ix_fact_ventas_asesor   ON FACT_VENTAS USING BTREE (asesor_sk);
CREATE INDEX ix_fact_ventas_garantia ON FACT_VENTAS USING BTREE (tiene_garantia_extendida);

-- -----------------------------------------------------------------------------
-- 2.2 FACT_DEVOLUCIONES
-- Grano: Un evento de reclamo, retorno físico o reembolso procesado para un ítem.
-- Trazabilidad: Mantiene acoplamiento atómico exacto 1:1 con la PK compuesta de 
-- FACT_VENTAS a través de (ticket_venta_origen, linea_venta_origen).
-- -----------------------------------------------------------------------------
CREATE TABLE FACT_DEVOLUCIONES (
    devolucion_sk       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- Llaves foráneas a dimensiones conformadas
    tiempo_sk           INTEGER NOT NULL REFERENCES DIM_TIEMPO(tiempo_sk),
    producto_sk         INTEGER NOT NULL REFERENCES DIM_PRODUCTO(producto_sk),
    cliente_sk          INTEGER NOT NULL REFERENCES DIM_CLIENTE(cliente_sk),
    sucursal_sk         INTEGER NOT NULL REFERENCES DIM_SUCURSAL(sucursal_sk), -- Sucursal receptora del reclamo

    -- Dimensiones degeneradas de control y enlace atómico
    num_devolucion      VARCHAR(30)  NOT NULL,
    ticket_venta_origen VARCHAR(30)  NOT NULL,
    linea_venta_origen  SMALLINT     NOT NULL DEFAULT 1, -- Cruce exacto con FACT_VENTAS.num_linea
    numero_serie        VARCHAR(50),
    motivo_devolucion   VARCHAR(100) NOT NULL,

    -- Métricas cuantitativas
    cantidad_devuelta   SMALLINT     NOT NULL CHECK (cantidad_devuelta > 0),
    monto_devolucion    NUMERIC(14,2) NOT NULL CHECK (monto_devolucion >= 0),

    CONSTRAINT uq_fact_devoluciones_num UNIQUE (num_devolucion)
);

COMMENT ON TABLE FACT_DEVOLUCIONES IS 
    'Hecho transaccional de posventa. Monitorea retornos físicos, causas de falla y notas de crédito generadas.';
COMMENT ON COLUMN FACT_DEVOLUCIONES.linea_venta_origen IS 
    'Identificador del renglón original facturado. Garantiza acoplamiento unívoco con FACT_VENTAS(num_ticket, num_linea).';
COMMENT ON COLUMN FACT_DEVOLUCIONES.sucursal_sk IS 
    'Supuesto ETL: Sucursal receptora del hardware devuelto (capturada por POS o heredada de la venta).';

-- Índices B-Tree para optimización de agregaciones de posventa y auditoría cruzada
CREATE INDEX ix_fact_devol_tiempo   ON FACT_DEVOLUCIONES USING BTREE (tiempo_sk);
CREATE INDEX ix_fact_devol_producto ON FACT_DEVOLUCIONES USING BTREE (producto_sk);
CREATE INDEX ix_fact_devol_cliente  ON FACT_DEVOLUCIONES USING BTREE (cliente_sk);
CREATE INDEX ix_fact_devol_sucursal ON FACT_DEVOLUCIONES USING BTREE (sucursal_sk);
CREATE INDEX ix_fact_devol_origen   ON FACT_DEVOLUCIONES USING BTREE (ticket_venta_origen, linea_venta_origen);

-- -----------------------------------------------------------------------------
-- 2.3 FACT_STOCK
-- Grano: Instantánea periódica (Periodic Snapshot) mensual/diaria por tiempo, sucursal y producto.
-- Justificación: PREPARACIÓN ARQUITECTÓNICA. En el caso oficial no se entregó fuente de 
-- almacén, pero se incluye formalmente para sustentar la fórmula de rotación financiera:
-- Rotación = SUM(FACT_VENTAS[costo_total_real]) / PROMEDIO(FACT_STOCK[costo_inventario_total]).
-- -----------------------------------------------------------------------------
CREATE TABLE FACT_STOCK (
    tiempo_sk               INTEGER NOT NULL REFERENCES DIM_TIEMPO(tiempo_sk),
    sucursal_sk             INTEGER NOT NULL REFERENCES DIM_SUCURSAL(sucursal_sk),
    producto_sk             INTEGER NOT NULL REFERENCES DIM_PRODUCTO(producto_sk),

    -- Métricas semi-aditivas (sumables en productos y tiendas, no sumables en el tiempo)
    cantidad_disponible     INTEGER NOT NULL CHECK (cantidad_disponible >= 0),
    cantidad_apartada       INTEGER NOT NULL DEFAULT 0 CHECK (cantidad_apartada >= 0), -- Mercancía comprometida por apartados (Regla #3)
    costo_inventario_total  NUMERIC(14,2) NOT NULL CHECK (costo_inventario_total >= 0), -- Existencias valorizadas

    PRIMARY KEY (tiempo_sk, sucursal_sk, producto_sk)
);

COMMENT ON TABLE FACT_STOCK IS 
    'Estructura preparatoria de Periodic Snapshot. Suministra el inventario promedio indispensable para la rotación.';
COMMENT ON COLUMN FACT_STOCK.cantidad_apartada IS 
    'Monitorea el inventario retenido por órdenes con abonos pendientes antes de su entrega definitiva.';

-- Índices secundarios para acelerar consultas analíticas filtradas por producto o sucursal
CREATE INDEX ix_fact_stock_producto ON FACT_STOCK USING BTREE (producto_sk);
CREATE INDEX ix_fact_stock_sucursal ON FACT_STOCK USING BTREE (sucursal_sk);

