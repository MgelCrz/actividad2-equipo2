-- -----------------------------------------------------------------------------
-- 1.1 DIM_TIEMPO
-- Grano: Un día calendario.
-- Justificación: Desacopla la marca temporal en jerarquías analíticas para evaluar 
-- estacionalidad, comportamiento en fines de semana y festivos.
-- -----------------------------------------------------------------------------
CREATE TABLE DIM_TIEMPO (
    tiempo_sk       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha           DATE        NOT NULL,
    dia             SMALLINT    NOT NULL,
    dia_semana      VARCHAR(15) NOT NULL,
    mes             SMALLINT    NOT NULL,
    nombre_mes      VARCHAR(15) NOT NULL,
    trimestre       SMALLINT    NOT NULL,
    anio            SMALLINT    NOT NULL,
    es_fin_semana   BOOLEAN     NOT NULL DEFAULT FALSE,
    es_festivo      BOOLEAN     NOT NULL DEFAULT FALSE,
    CONSTRAINT uq_dim_tiempo_fecha UNIQUE (fecha)
);

COMMENT ON TABLE DIM_TIEMPO IS 
    'Dimensión de tiempo conformada. Generada algorítmicamente para análisis de series históricas y estacionalidad.';
COMMENT ON COLUMN DIM_TIEMPO.tiempo_sk IS 
    'Surrogate Key del calendario. -1 = Fecha no definida o en trámite.';

-- Registro centinela para blindaje ante fechas no identificadas
INSERT INTO DIM_TIEMPO (tiempo_sk, fecha, dia, dia_semana, mes, nombre_mes, trimestre, anio, es_fin_semana, es_festivo)
VALUES (-1, DATE '1900-01-01', 1, 'No Definido', 1, 'No Definido', 1, 1900, FALSE, FALSE);

-- -----------------------------------------------------------------------------
-- 1.2 DIM_PRODUCTO
-- Grano: Un artículo o SKU del catálogo de hardware.
-- Justificación: Permite analizar la rentabilidad por marca, modelo y categoría. 
-- El atributo 'requiere_serie' implementa formalmente la Regla de Negocio #2.
-- -----------------------------------------------------------------------------
CREATE TABLE DIM_PRODUCTO (
    producto_sk     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    producto_id     VARCHAR(20)  NOT NULL, -- Llave natural en sistema transaccional
    sku             VARCHAR(30)  NOT NULL,
    nombre_producto VARCHAR(150) NOT NULL,
    marca           VARCHAR(60),
    categoria       VARCHAR(60),
    modelo          VARCHAR(60),
    costo_estandar  NUMERIC(12,2) CHECK (costo_estandar >= 0),
    requiere_serie  BOOLEAN      NOT NULL DEFAULT FALSE, -- Regla #2: Control de series
    CONSTRAINT uq_dim_producto_id UNIQUE (producto_id)
);

COMMENT ON TABLE DIM_PRODUCTO IS 
    'Catálogo maestro de hardware. Responde a ventas, márgenes brutos y mermas por marca, modelo y categoría.';
COMMENT ON COLUMN DIM_PRODUCTO.producto_sk IS 
    'Surrogate Key. -1 = Transacción de servicio puro o póliza sin hardware.';
COMMENT ON COLUMN DIM_PRODUCTO.requiere_serie IS 
    'Bandera operativa para hardware delicado que exige número de serie unitario (Regla #2).';

