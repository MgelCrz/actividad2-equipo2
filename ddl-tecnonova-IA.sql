VALUES (-1, 'N/A', 'No Identificado');

-- -----------------------------------------------------------------------------
-- Tabla de Hechos: FACT_VENTAS
-- -----------------------------------------------------------------------------

CREATE TABLE FACT_VENTAS (
    venta_sk                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tiempo_sk                   INTEGER NOT NULL REFERENCES DIM_TIEMPO(tiempo_sk),
    producto_sk                 INTEGER NOT NULL REFERENCES DIM_PRODUCTO(producto_sk),
    servicio_sk                 INTEGER NOT NULL REFERENCES DIM_SERVICIO(servicio_sk),
    cliente_sk                  INTEGER NOT NULL REFERENCES DIM_CLIENTE(cliente_sk),
    sucursal_sk                 INTEGER NOT NULL REFERENCES DIM_SUCURSAL(sucursal_sk),
    canal_sk                    INTEGER NOT NULL REFERENCES DIM_CANAL(canal_sk),
    asesor_sk                   INTEGER NOT NULL REFERENCES DIM_ASESOR(asesor_sk),
    metodo_pago_sk              INTEGER NOT NULL REFERENCES DIM_METODO_PAGO(metodo_pago_sk),

    num_ticket                  VARCHAR(30) NOT NULL,
    num_linea                   SMALLINT NOT NULL,
    numero_serie                VARCHAR(50),
    lote_compra                 VARCHAR(30),

    cantidad                    SMALLINT NOT NULL CHECK (cantidad > 0),
    precio_unitario             NUMERIC(12,2) NOT NULL CHECK (precio_unitario >= 0),
    costo_unitario_real         NUMERIC(12,2) NOT NULL CHECK (costo_unitario_real >= 0),
    monto_bruto                 NUMERIC(14,2) NOT NULL,
    monto_descuento             NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (monto_descuento >= 0),
    monto_neto_venta            NUMERIC(14,2) NOT NULL,
    costo_total_real            NUMERIC(14,2) NOT NULL,
    margen_bruto                NUMERIC(14,2) NOT NULL,
    monto_comision_marketplace  NUMERIC(14,2) NOT NULL DEFAULT 0,
    margen_neto_real            NUMERIC(14,2) NOT NULL,

    CONSTRAINT uq_fact_ventas_ticket_linea UNIQUE (num_ticket, num_linea),
    CONSTRAINT chk_monto_bruto CHECK (monto_bruto = cantidad * precio_unitario),
    CONSTRAINT chk_monto_neto CHECK (monto_neto_venta = monto_bruto - monto_descuento),
    CONSTRAINT chk_costo_total CHECK (costo_total_real = cantidad * costo_unitario_real),
    CONSTRAINT chk_margen_bruto CHECK (margen_bruto = monto_neto_venta - costo_total_real),
    CONSTRAINT chk_margen_neto CHECK (margen_neto_real = margen_bruto - monto_comision_marketplace)
);

CREATE INDEX ix_fact_ventas_tiempo   ON FACT_VENTAS (tiempo_sk);
CREATE INDEX ix_fact_ventas_producto ON FACT_VENTAS (producto_sk);
CREATE INDEX ix_fact_ventas_cliente  ON FACT_VENTAS (cliente_sk);
CREATE INDEX ix_fact_ventas_sucursal ON FACT_VENTAS (sucursal_sk);
CREATE INDEX ix_fact_ventas_canal    ON FACT_VENTAS (canal_sk);
CREATE INDEX ix_fact_ventas_asesor   ON FACT_VENTAS (asesor_sk);

-- -----------------------------------------------------------------------------
-- Tabla de Hechos: FACT_DEVOLUCIONES
-- -----------------------------------------------------------------------------

CREATE TABLE FACT_DEVOLUCIONES (
    devolucion_sk       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tiempo_sk           INTEGER NOT NULL REFERENCES DIM_TIEMPO(tiempo_sk),
    producto_sk         INTEGER NOT NULL REFERENCES DIM_PRODUCTO(producto_sk),
    cliente_sk          INTEGER NOT NULL REFERENCES DIM_CLIENTE(cliente_sk),
    sucursal_sk         INTEGER NOT NULL REFERENCES DIM_SUCURSAL(sucursal_sk),

    num_devolucion      VARCHAR(30) NOT NULL UNIQUE,
    ticket_venta_origen VARCHAR(30) NOT NULL,
    numero_serie        VARCHAR(50),
    motivo_devolucion   VARCHAR(100) NOT NULL,

    cantidad_devuelta   SMALLINT NOT NULL CHECK (cantidad_devuelta > 0),
    monto_devolucion    NUMERIC(14,2) NOT NULL CHECK (monto_devolucion >= 0)
);

CREATE INDEX ix_fact_devol_tiempo   ON FACT_DEVOLUCIONES (tiempo_sk);
CREATE INDEX ix_fact_devol_producto ON FACT_DEVOLUCIONES (producto_sk);
CREATE INDEX ix_fact_devol_sucursal ON FACT_DEVOLUCIONES (sucursal_sk);
CREATE INDEX ix_fact_devol_origen   ON FACT_DEVOLUCIONES (ticket_venta_origen);

-- -----------------------------------------------------------------------------
-- Tabla de Hechos: FACT_STOCK
-- -----------------------------------------------------------------------------

CREATE TABLE FACT_STOCK (
    tiempo_sk               INTEGER NOT NULL REFERENCES DIM_TIEMPO(tiempo_sk),
    sucursal_sk             INTEGER NOT NULL REFERENCES DIM_SUCURSAL(sucursal_sk),
    producto_sk             INTEGER NOT NULL REFERENCES DIM_PRODUCTO(producto_sk),
    cantidad_disponible     INTEGER NOT NULL CHECK (cantidad_disponible >= 0),
    cantidad_apartada       INTEGER NOT NULL DEFAULT 0 CHECK (cantidad_apartada >= 0),
    costo_inventario_total  NUMERIC(14,2) NOT NULL CHECK (costo_inventario_total >= 0),
    PRIMARY KEY (tiempo_sk, sucursal_sk, producto_sk)
);

CREATE INDEX ix_fact_stock_producto ON FACT_STOCK (producto_sk);
CREATE INDEX ix_fact_stock_sucursal ON FACT_STOCK (sucursal_sk);
