CREATE TABLE DIM_SERVICIO (
    servicio_sk     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    servicio_id     VARCHAR(20) NOT NULL UNIQUE,
    tipo_servicio   VARCHAR(40),
    nombre_servicio VARCHAR(100),
    tarifa_base     NUMERIC(12,2) CHECK (tarifa_base >= 0)
