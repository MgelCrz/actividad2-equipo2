CREATE TABLE DIM_ASESOR (
    asesor_sk     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asesor_id     VARCHAR(20) NOT NULL UNIQUE,
    nombre_asesor VARCHAR(150) NOT NULL,
    nivel         VARCHAR(30)
);

INSERT INTO DIM_ASESOR (asesor_sk, asesor_id, nombre_asesor)
