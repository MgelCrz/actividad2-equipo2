    sucursal_id     VARCHAR(20) NOT NULL UNIQUE,
    nombre_sucursal VARCHAR(100) NOT NULL,
    ciudad          VARCHAR(80),
    region          VARCHAR(60),
    tipo_nodo       VARCHAR(30)
);

INSERT INTO DIM_SUCURSAL (sucursal_sk, sucursal_id, nombre_sucursal)
VALUES (-1, 'N/A', 'Digital / Sin Asignar');

CREATE TABLE DIM_CANAL (
    canal_sk              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    canal_id              VARCHAR(20) NOT NULL UNIQUE,
    canal                 VARCHAR(40) NOT NULL,
